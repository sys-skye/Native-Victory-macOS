//! The lock-file part of [`crate::SOURCE_HASH`] (`lock.rs`, included by `build.rs`).

include!("../lock.rs");

/// A lock file in Cargo's layout: the translator, two of its dependencies (one of them with a
/// dependency of its own, held in two versions), and an app crate with a dependency of its own.
fn lock(app_dependency: &str, inner: &str) -> String {
    format!(
        r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "adler2"
version = "{inner}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "adler2"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "clap",
 "victory-shader",
]

[[package]]
name = "clap"
version = "{app_dependency}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "cccc"

[[package]]
name = "miniz_oxide"
version = "0.8.9"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "dddd"
dependencies = [
 "adler2 {inner}",
]

[[package]]
name = "thiserror"
version = "2.0.17"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "eeee"
dependencies = []

[[package]]
name = "victory-shader"
version = "0.1.0"
dependencies = [
 "miniz_oxide",
 "thiserror",
]
"#
    )
}

#[test]
fn the_key_takes_the_translator_s_dependencies_only() {
    let base = dependency_entries(&lock("4.5.0", "2.0.1"), "victory-shader");
    assert_eq!(
        base,
        [
            "adler2 2.0.1 registry+https://github.com/rust-lang/crates.io-index aaaa",
            "miniz_oxide 0.8.9 registry+https://github.com/rust-lang/crates.io-index dddd",
            "thiserror 2.0.17 registry+https://github.com/rust-lang/crates.io-index eeee",
        ]
    );
    // An app's dependency changing leaves the translator's part alone (it used to make every
    // cached translation cold, #334).
    assert_eq!(dependency_entries(&lock("4.6.0", "2.0.1"), "victory-shader"), base);
    // A dependency of a dependency changing does change it.
    assert_ne!(dependency_entries(&lock("4.5.0", "2.0.2"), "victory-shader"), base);
}

#[test]
fn the_workspace_lock_file_names_the_translator_s_dependencies() {
    let text = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../Cargo.lock")).unwrap();
    let entries = dependency_entries(&text, "victory-shader");
    for name in ["miniz_oxide ", "thiserror "] {
        assert!(entries.iter().any(|e| e.starts_with(name)), "{name}in {entries:?}");
    }
    assert!(!entries.iter().any(|e| e.starts_with("victory-shader ")));
}
